# Stubs for the Xbox imports of the generated code that the SDK does not define.
#
# Generated code calls every kernel import as __imp__<Name> (declared in the
# generated init header with DECLARE_REX_FUNC(__imp__<Name>)); the kernel
# defines the ones it implements with REX_EXPORT / REX_EXPORT_STUB. An import
# that nobody defines would be an undefined symbol at link time. For each of
# them this script writes a definition that stops the run through
# rex::diagnostics::StopAtMissingFunction, so the NRO links and the first call
# is recorded (tools/switch-game/main.cpp).
#
# The defined names come from `nm` on the SDK archives actually linked, so a
# stub never shadows a real export.
#
# Usage:
#   python missing_imports.py --header gta4_init.h --nm aarch64-none-elf-nm
#       --out missing_imports.cpp --list missing_imports.txt lib1.a [lib2.a ...]
import argparse
import re
import subprocess
import sys

IMPORT_RE = re.compile(r'^DECLARE_REX_FUNC\((__imp__[A-Za-z0-9_]+)\);', re.M)


def defined_symbols(nm, libs):
    names = set()
    for lib in libs:
        out = subprocess.run([nm, '-g', '--defined-only', lib], capture_output=True, text=True,
                             check=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 3:
                names.add(parts[2])
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--header', required=True)
    ap.add_argument('--nm', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--list', required=True)
    ap.add_argument('libs', nargs='+')
    args = ap.parse_args()

    with open(args.header, encoding='utf-8') as f:
        imports = sorted(set(IMPORT_RE.findall(f.read())))
    defined = defined_symbols(args.nm, args.libs)
    missing = [name for name in imports if name not in defined]

    lines = [
        '// Generated by tools/switch-game/missing_imports.py - DO NOT EDIT.',
        f'// {len(missing)} of the {len(imports)} imports of the generated code have no',
        '// definition in the SDK: each one stops the run on its first call.',
        '#include <rex/diagnostics/missing_function.h>',
        '#include <rex/ppc.h>',
        '',
    ]
    for name in missing:
        export = name[len('__imp__'):]
        lines.append(f'extern "C" REX_FUNC({name}) {{')
        lines.append('  (void)base;')
        lines.append('  rex::diagnostics::StopAtMissingFunction("Xbox export not implemented by the SDK",')
        lines.append(f'                                          "{export}", uint32_t(ctx.lr));')
        lines.append('}')
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    with open(args.list, 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'{len(missing)} of {len(imports)} imports missing from the SDK\n')
        for name in missing:
            f.write(name[len('__imp__'):] + '\n')
    print(f'missing_imports: {len(missing)} of {len(imports)} imports have no SDK definition')
    return 0


if __name__ == '__main__':
    sys.exit(main())
